-- Orders, payment attempts, settlement records and the coupon ledgers.
-- Runs after plan_prices (price_id) and coupons (payment_order_discounts).
-- coupon_redemptions lives here, not in 02, because it references both
-- payment_orders and coupons; this is the order the spec's §4.9 note sets.

CREATE TABLE IF NOT EXISTS payment_orders (
    id                 TEXT PRIMARY KEY,
    numeric_code       BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    code               TEXT NOT NULL UNIQUE,
    product_id         TEXT NOT NULL REFERENCES products(id),
    plan_id            TEXT NOT NULL REFERENCES plans(id),
    price_id           TEXT NULL REFERENCES plan_prices(id),
    license_id         TEXT NULL REFERENCES licenses(id) ON DELETE SET NULL,
    email              TEXT NOT NULL,
    kind               TEXT NOT NULL CHECK (kind IN ('new','renewal','upgrade','addon')),
    quantity           INT NOT NULL DEFAULT 1 CHECK (quantity > 0),
    subtotal_minor     BIGINT NOT NULL CHECK (subtotal_minor >= 0),
    discount_minor     BIGINT NOT NULL DEFAULT 0 CHECK (discount_minor >= 0),
    tax_minor          BIGINT NOT NULL DEFAULT 0 CHECK (tax_minor >= 0),
    total_minor        BIGINT NOT NULL CHECK (total_minor >= 0),
    currency           CHAR(3) NOT NULL,
    currency_exponent  SMALLINT NOT NULL,
    tax_rate_bp        INT NOT NULL DEFAULT 0,
    provider           TEXT NOT NULL,
    status             TEXT NOT NULL CHECK (status IN
                         ('pending','paid','expired','canceled','refunded','partially_refunded')),
    expires_at         TIMESTAMPTZ NOT NULL,
    paid_at            TIMESTAMPTZ,
    period_start       TIMESTAMPTZ,
    period_end         TIMESTAMPTZ,
    buyer              JSONB NOT NULL DEFAULT '{}'::jsonb,
    metadata           JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by_api_key_id TEXT NULL REFERENCES api_keys(id) ON DELETE SET NULL,
    last_settlement_error TEXT NOT NULL DEFAULT '',
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS payment_orders_status_idx ON payment_orders (status, expires_at);
CREATE INDEX IF NOT EXISTS payment_orders_license_idx ON payment_orders (license_id, created_at DESC);
CREATE INDEX IF NOT EXISTS payment_orders_email_idx ON payment_orders (lower(email), created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS payment_orders_renewal_once
    ON payment_orders (license_id, period_end) WHERE kind = 'renewal' AND status = 'pending';

-- Discounts are rows, not a coupon_id column on the order, so stacking
-- and a coupon deletion (SET NULL) leave the applied code and amount on
-- the order.
CREATE TABLE IF NOT EXISTS payment_order_discounts (
    id            TEXT PRIMARY KEY,
    order_id      TEXT NOT NULL REFERENCES payment_orders(id) ON DELETE CASCADE,
    coupon_id     TEXT NULL REFERENCES coupons(id) ON DELETE SET NULL,
    coupon_code   TEXT NOT NULL,
    type          TEXT NOT NULL CHECK (type IN ('percent','fixed')),
    value         BIGINT NOT NULL,
    amount_minor  BIGINT NOT NULL CHECK (amount_minor >= 0),
    priority      INT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (order_id, coupon_code)
);
CREATE INDEX IF NOT EXISTS payment_order_discounts_coupon_idx ON payment_order_discounts (coupon_id);

-- One provider-side instruction per attempt. raw holds the adapter's
-- response so the pay page and the reconciler can read it back without
-- another provider call.
CREATE TABLE IF NOT EXISTS payment_attempts (
    id            TEXT PRIMARY KEY,
    order_id      TEXT NOT NULL REFERENCES payment_orders(id) ON DELETE CASCADE,
    provider      TEXT NOT NULL,
    provider_ref  TEXT NOT NULL DEFAULT '',
    status        TEXT NOT NULL CHECK (status IN
                    ('created','pending','succeeded','failed','expired','canceled')),
    amount_minor  BIGINT NOT NULL CHECK (amount_minor >= 0),
    currency      CHAR(3) NOT NULL,
    qr_payload    TEXT NOT NULL DEFAULT '',
    checkout_url  TEXT NOT NULL DEFAULT '',
    va_number     TEXT NOT NULL DEFAULT '',
    raw           JSONB NOT NULL DEFAULT '{}'::jsonb,
    expires_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS payment_attempts_provider_ref
    ON payment_attempts (provider, provider_ref) WHERE provider_ref <> '';
CREATE INDEX IF NOT EXISTS payment_attempts_order_idx ON payment_attempts (order_id);

-- Bank/webhook transfers, matched or not. The unique provider ref is the
-- dedupe that makes webhook redelivery harmless.
CREATE TABLE IF NOT EXISTS payment_transactions (
    id            TEXT PRIMARY KEY,
    provider      TEXT NOT NULL,
    provider_ref  TEXT NOT NULL,
    order_id      TEXT NULL REFERENCES payment_orders(id) ON DELETE SET NULL,
    amount_minor  BIGINT NOT NULL,
    currency      CHAR(3) NOT NULL,
    status        TEXT NOT NULL CHECK (status IN ('matched','unmatched','ignored')),
    ignore_reason TEXT NOT NULL DEFAULT '',
    raw           JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at   TIMESTAMPTZ NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS payment_transactions_provider_ref
    ON payment_transactions (provider, provider_ref);
CREATE INDEX IF NOT EXISTS payment_transactions_unmatched_idx
    ON payment_transactions (status, occurred_at DESC);
CREATE INDEX IF NOT EXISTS payment_transactions_order_idx ON payment_transactions (order_id);

-- Audit trail of raw provider payloads. processed_events remains the
-- claim/done idempotency mechanism; this table is what the payload was.
CREATE TABLE IF NOT EXISTS payment_events (
    id          TEXT PRIMARY KEY,
    provider    TEXT NOT NULL,
    event_id    TEXT NOT NULL,
    order_id    TEXT NULL REFERENCES payment_orders(id) ON DELETE SET NULL,
    kind        TEXT NOT NULL,
    raw         JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS payment_events_unique ON payment_events (provider, event_id);

CREATE TABLE IF NOT EXISTS payment_refunds (
    id           TEXT PRIMARY KEY,
    order_id     TEXT NOT NULL REFERENCES payment_orders(id) ON DELETE RESTRICT,
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
    currency     CHAR(3) NOT NULL,
    reason       TEXT NOT NULL DEFAULT '',
    method       TEXT NOT NULL CHECK (method IN ('manual','sepay','payos')),
    provider_ref TEXT NOT NULL DEFAULT '',
    status       TEXT NOT NULL CHECK (status IN ('requested','pending','succeeded','failed')),
    created_by   TEXT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS payment_refunds_order_idx ON payment_refunds (order_id);

CREATE TABLE IF NOT EXISTS coupon_redemptions (
    id                    TEXT PRIMARY KEY,
    coupon_id             TEXT NOT NULL REFERENCES coupons(id) ON DELETE RESTRICT,
    coupon_code           TEXT NOT NULL,
    order_id              TEXT NOT NULL REFERENCES payment_orders(id) ON DELETE CASCADE,
    email                 TEXT NOT NULL DEFAULT '',
    external_customer_id  TEXT NOT NULL DEFAULT '',
    type                  TEXT NOT NULL CHECK (type IN ('percent','fixed','trial')),
    amount_minor          BIGINT NOT NULL DEFAULT 0,
    trial_days            INT NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (order_id, coupon_code)
);
CREATE INDEX IF NOT EXISTS coupon_redemptions_customer_idx
    ON coupon_redemptions (coupon_id, email, external_customer_id);
CREATE INDEX IF NOT EXISTS coupon_redemptions_coupon_idx
    ON coupon_redemptions (coupon_id, created_at DESC);

CREATE TABLE IF NOT EXISTS payment_sync_cursors (
    id                  TEXT PRIMARY KEY,
    provider            TEXT NOT NULL,
    scope               TEXT NOT NULL DEFAULT 'default',
    last_transaction_id TEXT NOT NULL DEFAULT '',
    last_synced_at      TIMESTAMPTZ,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS payment_sync_cursors_unique ON payment_sync_cursors (provider, scope);
